import numpy as np


# Defining U_0, the reference potential
# U0
def U1(xx: np.ndarray) -> np.ndarray:
    return (
            -0.01059423355572770
            * np.tanh((xx - 0.01453708425609560) / (9.089868397988610 * 10 ** (-5)))
            + 0.02443615203087110 * np.tanh((xx - 0.5464261369950400) / (0.6270508166379020))
            - 0.01637520788053810
            * np.tanh((xx - 0.5639025014475490) / (0.07053886409518520))
            - 0.06542365622896410 * np.tanh((xx - 0.5960370524233590) / (1.409966536648620))
            - 0.04173226059293490
            * np.tanh((xx - 0.1787670587868640) / (0.07693844911793470))
            - 0.4792178163846890
            * np.tanh((xx + 0.003845707852011820) / (0.04112633446959460))
            - 0.04364293924074990
            * np.tanh((xx - 0.09449231893318330) / (-0.02046776012570780))
            - 0.08241166396760410
            * np.tanh((xx - 0.07746685789572230) / (0.03593817905677970))
            + 0.6594735004847470
    )


def U2(xx: np.ndarray) -> np.ndarray:
    return (
            4.466520763420150 * xx ** 6
            - 1.163251395483540 * xx ** 5
            - 597.3328922807720 * xx ** 4
            + 2173.321763906580 * xx ** 3
            - 3005.282176279630 * xx ** 2
            + 1857.779353226540 * xx
            - 431.7897183333920
    )


def Ueq(xx: np.ndarray) -> np.ndarray:
    """The half-cell open-circuit potential of the graphite"""
    return U1(xx) + (U2(xx) - U1(xx)) / (1.0 + np.exp(-100 * (xx - 0.8627886168611160)))


